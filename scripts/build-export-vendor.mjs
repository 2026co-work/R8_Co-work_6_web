import { build } from 'vite';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
const outDir = resolve(root, 'vendor');
await mkdir(outDir, { recursive: true });
await build({
  configFile: false,
  root,
  build: {
    lib: { entry: resolve(root, 'scripts/export-vendor-entry.js'), formats: ['es'], fileName: () => 'export-libraries.js' },
    outDir,
    emptyOutDir: false,
    minify: true,
    rolldownOptions: { output: { codeSplitting: false } },
  },
});
// 同梱パッケージのライセンスを配布ファイルに残す。
const lock = JSON.parse(await readFile(resolve(root, 'package-lock.json'), 'utf8'));
const notices = ['Generated by npm run vendor:export. Do not edit export-libraries.js by hand.\n'];
for (const [directory, meta] of Object.entries(lock.packages)) {
  if (!directory || meta.dev) continue;
  for (const name of ['LICENSE', 'LICENSE.txt', 'LICENSE.md', 'license', 'license.txt', 'License.txt', 'LICENSE-MIT.txt']) {
    try {
      const license = await readFile(resolve(root, directory, name), 'utf8');
      notices.push(`${directory} (${meta.version})\n${'='.repeat(60)}\n${license}`);
      break;
    } catch (error) { if (error.code !== 'ENOENT') throw error; }
  }
}
await writeFile(resolve(outDir, 'THIRD_PARTY_LICENSES.txt'), notices.join('\n\n'));
