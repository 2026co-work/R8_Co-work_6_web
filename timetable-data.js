// 二重枠の領域だけ学科対象。行に隣接する「M・1組」などを同じ集団と解釈しない。
function isDepartmentCell(grade, column) {
  if (grade === 1) return column <= 3 || column === 10;
  if (grade === 2) return column === 2 || (column >= 4 && column <= 7) || column >= 18;
  return true;
}

function parseSourceText(text) {
  const lines = text.trim().split('\n').map(line => line.trim()).filter(Boolean);
  const unwrap = value => value.replace(/([A-Za-z])\n(?=[A-Za-z])/g, '$1 ').replace(/\n/g, '').trim();
  const locationMatch = text.match(/[［\[]([^］\]]+)[］\]]/);
  if (locationMatch) {
    return {
      subjectName: unwrap(text.slice(0, locationMatch.index)),
      location: locationMatch[1],
      teacher: text.slice(locationMatch.index + locationMatch[0].length).replace(/\n/g, '').trim()
    };
  }
  if (lines[0] === 'HR') return { subjectName: 'HR', location: '', teacher: lines.slice(1).join(' ') };
  return { subjectName: unwrap(lines.slice(0, -1).join('\n')), location: '', teacher: lines.at(-1) || '' };
}

function sourceTargets(cell) {
  const targets = [];
  for (let row = cell.rowStart; row <= cell.rowEnd; row++) {
    if (row < 8) {
      const grade = row < 4 ? 1 : 2;
      const group = row % 4;
      const targetType = isDepartmentCell(grade, cell.columnStart) ? 'department' : 'class';
      targets.push({ grade, targetType, targetGroup: targetType === 'class' ? String(group + 1) : DEPARTMENTS[group] });
    } else if (row < 16) {
      const group = Math.floor((row - 8) / 2);
      targets.push({ grade: 3, targetType: 'department', targetGroup: DEPARTMENTS[group], studentType: row % 2 === 0 ? 'regular' : 'international' });
    } else {
      const grade = row < 21 ? 4 : 5;
      const group = (row - (grade === 4 ? 16 : 21));
      const course = ['M', 'ED', 'EJ', 'C', 'A'][group];
      targets.push({ grade, targetType: 'department', targetGroup: course.startsWith('E') ? 'E' : course, ...(course.startsWith('E') ? { course } : {}) });
    }
  }
  return targets;
}

const LESSONS = SOURCE_CELLS.flatMap(cell => {
  // 音楽・美術は原本で1・2組、3・4組を縦結合した選択授業。両方を必修扱いしない。
  const artParts = cell.text.includes('音楽-2') && cell.text.includes('美術-2')
    ? [{ text: cell.text.split('美術-2')[0].trim(), arts: 'music' }, { text: `美術-2${cell.text.split('美術-2')[1]}`.trim(), arts: 'art' }]
    : [{ text: cell.text }];
  return sourceTargets(cell).flatMap((target, targetIndex) => artParts.map((part, partIndex) => ({
    id: `${cell.id}-${targetIndex}-${partIndex}`,
    ...target,
    ...parseSourceText(part.text),
    dayOfWeek: Math.floor(cell.columnStart / 4) + 1,
    period: cell.columnStart % 4 + 1,
    duration: cell.columnEnd - cell.columnStart + 1,
    notes: part.arts ? '芸術選択科目' : '',
    ...(part.arts ? { arts: part.arts } : {}),
    changeInfo: null,
    sourceCellId: cell.id,
    sourceText: part.text
  })));
});

function generateTimetable(data, selection) {
  const { grade, department, classGroup, course, studentType = 'regular', arts = 'music' } = selection;
  if (!Number.isInteger(grade) || grade < 1 || grade > 5 || !DEPARTMENTS.includes(department)) {
    throw new Error('学年と学科を正しく選択してください。');
  }
  if (grade <= 2 && !['1', '2', '3', '4'].includes(classGroup)) {
    throw new Error('1・2年生はクラスを選択してください。');
  }
  if (grade >= 4 && department === 'E' && !['ED', 'EJ'].includes(course)) {
    throw new Error('4・5年生のE学科はED・EJを選択してください。');
  }
  if (!['regular', 'international'].includes(studentType)) throw new Error('留学生の区分を選択してください。');
  if (grade === 1 && !['music', 'art'].includes(arts)) throw new Error('音楽・美術を選択してください。');
  const selected = data.filter(lesson => {
    if (lesson.grade !== grade) return false;
    if (lesson.course && lesson.course !== course) return false;
    if (lesson.studentType && lesson.studentType !== studentType) return false;
    if (lesson.arts && lesson.arts !== arts) return false;
    const matchesDepartment = lesson.targetType === 'department' && lesson.targetGroup === department;
    const matchesClass = grade <= 2 && lesson.targetType === 'class' && lesson.targetGroup === classGroup;
    return matchesDepartment || matchesClass;
  });

  // 5日 × 4限。セルを配列にして、重複を上書きせず検出できるようにする。
  const grid = Array.from({ length: 5 }, () => Array.from({ length: 4 }, () => []));
  for (const lesson of selected) {
    const duration = lesson.duration ?? 1;
    if (!Number.isInteger(lesson.dayOfWeek) || lesson.dayOfWeek < 1 || lesson.dayOfWeek > 5 ||
        !Number.isInteger(lesson.period) || lesson.period < 1 ||
        !Number.isInteger(duration) || duration < 1 || lesson.period + duration - 1 > 4) {
      throw new Error(`授業 ${lesson.id} の曜日・時限が不正です。`);
    }
    for (let offset = 0; offset < duration; offset++) {
      grid[lesson.dayOfWeek - 1][lesson.period - 1 + offset].push(lesson);
    }
  }
  const conflicts = grid.flat().filter(cell => cell.length > 1).length;
  return { selected, grid, conflicts };
}


